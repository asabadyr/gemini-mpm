#!/usr/bin/env bash
# agy-mpm-kit installer, runtime doctor & edition switcher for Google Antigravity (v2.3.1).
# Manages the ~/.gemini/config/plugins/agy-mpm-core symlink and Python pin file.
# NEVER reads or modifies ~/.gemini/config/config.json.

set -euo pipefail

PLUGIN_DIR_NAME="agy-mpm-core"
PLUGINS_ROOT="${AGY_PLUGINS_DIR:-${HOME}/.gemini/config/plugins}"
TARGET_LINK="${PLUGINS_ROOT}/${PLUGIN_DIR_NAME}"

if [ -n "${AGY_CONFIG_DIR:-}" ]; then
  CONFIG_DIR="${AGY_CONFIG_DIR}"
elif [ -n "${AGY_PLUGINS_DIR:-}" ]; then
  CONFIG_DIR="$(dirname "${AGY_PLUGINS_DIR}")"
else
  CONFIG_DIR="${HOME}/.gemini/config"
fi
PIN_FILE="${CONFIG_DIR}/agy-mpm-core.env"

# Resolve repository root portably even if invoked via relative path or symlink
resolve_script_dir() {
  local src="${BASH_SOURCE[0]}"
  while [ -L "${src}" ]; do
    local dir
    dir="$(cd -P "$(dirname "${src}")" && pwd)"
    src="$(readlink "${src}")"
    [[ "${src}" != /* ]] && src="${dir}/${src}"
  done
  cd -P "$(dirname "${src}")" && pwd
}

REPO_ROOT="$(resolve_script_dir)"

usage() {
  cat <<'EOF'
agy-mpm-kit — Installer & Edition Switcher (v2.3.1)

Usage:
  ./install.sh [--lang en|ru] [--python <path>] [--venv[=<backend>]] [--no-pin] [--force]
  ./install.sh --status
  ./install.sh --doctor
  ./install.sh --migrate [--check-projects <dir...>]
  ./install.sh --check-projects <dir...>
  ./install.sh --uninstall
  ./install.sh --help

Options:
  --lang <en|ru>              Install or switch active plugin edition (default: en)
                                en -> symlinks repo root (English rules & templates)
                                ru -> symlinks ./ru      (Native Russian rules & templates)
  --python <path>             Explicit Python >=3.8 executable to pin to agy-mpm-core.env
  --venv[=<backend>]          Create isolated kit .venv (backend: auto, uv, virtualenv, stdlib)
  --no-pin                    Skip writing Python pin to agy-mpm-core.env
  --status                    Show installation state, active edition, and Python runtime status
  --doctor                    Full environment and safety hook health diagnostic
  --migrate                   Migrate from pre-v2.3 installation (backs up legacy, pins Python, tests)
  --check-projects <dir...>   Inspect workspace directories for stale adapters & missing gitignores
  --uninstall                 Remove plugin symlink and Python pin file
  --force                     Replace existing non-symlink directory (backs up with .bak.<timestamp>)
  -h, --help                  Show this help message and exit

Notes:
  - Antigravity discovers plugin changes automatically (no IDE restart required).
  - Toggle the plugin on/off anytime in 1 click via /plugin (customization://agy-mpm-core).
  - This script NEVER modifies ~/.gemini/config/config.json.
EOF
}

is_valid_py() {
  local cand="$1"
  [ -n "${cand}" ] && [ -x "${cand}" ] && "${cand}" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 8) else 1)' >/dev/null 2>&1
}

get_py_version() {
  local cand="$1"
  "${cand}" -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}")' 2>/dev/null || true
}

read_version() {
  local manifest="$1"
  if [ -f "${manifest}" ]; then
    sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "${manifest}" | head -n 1
  fi
}

detect_edition() {
  local link_target="$1"
  local resolved=""
  if [ -d "${link_target}" ]; then
    resolved="$(cd -P "${link_target}" 2>/dev/null && pwd || true)"
  fi

  if [ "${resolved}" = "${REPO_ROOT}/ru" ] || [[ "${link_target}" == */ru ]]; then
    printf "ru (Russian edition)"
  elif [ "${resolved}" = "${REPO_ROOT}" ]; then
    printf "en (English edition)"
  else
    printf "external/custom (%s)" "${link_target}"
  fi
}

read_pinned_py() {
  if [ -f "${PIN_FILE}" ]; then
    sed -n -e 's/^[[:space:]]*AGY_MPM_PYTHON[[:space:]]*=[[:space:]]*"\([^"]*\)".*/\1/p' \
           -e 's/^[[:space:]]*AGY_MPM_PYTHON[[:space:]]*=[[:space:]]*'\''\([^'\'']*\)'\''.*/\1/p' \
           -e 's/^[[:space:]]*AGY_MPM_PYTHON[[:space:]]*=[[:space:]]*\([^[:space:]#]*\).*/\1/p' "${PIN_FILE}" 2>/dev/null | head -n 1
  fi
}

pin_python() {
  local py_path="$1"
  mkdir -p "${CONFIG_DIR}"
  cat <<EOF > "${PIN_FILE}"
# Generated by agy-mpm-kit install.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# Pinned Python executable for agy-mpm-core hooks and scripts (portable across GUI IDE and CLI)
AGY_MPM_PYTHON="${py_path}"
EOF
  chmod 0644 "${PIN_FILE}" 2>/dev/null || true
  printf "Pinned Python: %s -> %s\n" "${py_path}" "${PIN_FILE}"
}

create_kit_venv() {
  local backend="${1:-auto}"
  local venv_dir="${REPO_ROOT}/.venv"
  local created=false

  case "${backend}" in
    auto)
      if command -v uv >/dev/null 2>&1; then
        printf "Creating kit venv via uv...\n"
        uv venv "${venv_dir}" --python ">=3.8" && created=true || true
      fi
      if [ "${created}" != "true" ] && command -v virtualenv >/dev/null 2>&1; then
        printf "Creating kit venv via virtualenv...\n"
        virtualenv -p python3 "${venv_dir}" && created=true || true
      fi
      if [ "${created}" != "true" ]; then
        local sys_py
        sys_py="$("${REPO_ROOT}/scripts/mpm-py" --print-python 2>/dev/null || true)"
        if [ -n "${sys_py}" ] && is_valid_py "${sys_py}"; then
          printf "Creating kit venv via stdlib venv (%s)...\n" "${sys_py}"
          "${sys_py}" -m venv --without-pip "${venv_dir}" 2>/dev/null || "${sys_py}" -m venv "${venv_dir}"
          created=true
        fi
      fi
      ;;
    uv)
      if command -v uv >/dev/null 2>&1; then
        uv venv "${venv_dir}" --python ">=3.8"
        created=true
      else
        printf "Error: 'uv' command not found.\n" >&2
        return 1
      fi
      ;;
    virtualenv)
      if command -v virtualenv >/dev/null 2>&1; then
        virtualenv -p python3 "${venv_dir}"
        created=true
      else
        printf "Error: 'virtualenv' command not found.\n" >&2
        return 1
      fi
      ;;
    stdlib)
      local sys_py
      sys_py="$("${REPO_ROOT}/scripts/mpm-py" --print-python 2>/dev/null || true)"
      if [ -z "${sys_py}" ] && command -v python3 >/dev/null 2>&1 && is_valid_py "$(command -v python3)"; then
        sys_py="$(command -v python3)"
      fi
      if [ -n "${sys_py}" ] && is_valid_py "${sys_py}"; then
        "${sys_py}" -m venv --without-pip "${venv_dir}" 2>/dev/null || "${sys_py}" -m venv "${venv_dir}"
        created=true
      else
        printf "Error: Valid Python >= 3.8 not found for stdlib venv.\n" >&2
        return 1
      fi
      ;;
    *)
      printf "Error: Unknown venv backend '%s'. Expected auto, uv, virtualenv, or stdlib.\n" "${backend}" >&2
      return 1
      ;;
  esac

  local venv_py="${venv_dir}/bin/python3"
  [ ! -x "${venv_py}" ] && venv_py="${venv_dir}/bin/python"

  if [ "${created}" = "true" ] && is_valid_py "${venv_py}"; then
    printf "Successfully created kit virtualenv: %s (v%s)\n" "${venv_dir}" "$(get_py_version "${venv_py}")"
    return 0
  else
    printf "Error: Failed to create valid virtualenv at %s\n" "${venv_dir}" >&2
    return 1
  fi
}

run_guard_smoke_test() {
  local lang_arg="${1:-}"
  local p_clean='{"hookEventName": "PreToolUse", "cwd": "/tmp", "toolCall": {"name": "run_command", "args": {"CommandLine": "git clean -fd"}}}'
  local p_status='{"hookEventName": "PreToolUse", "cwd": "/tmp", "toolCall": {"name": "run_command", "args": {"CommandLine": "git status"}}}'

  local out_clean
  out_clean="$(printf '%s' "${p_clean}" | "${REPO_ROOT}/scripts/mpm-py" "${REPO_ROOT}/scripts/destructive-cmd-guard.py" ${lang_arg} 2>/dev/null || true)"
  local out_status
  out_status="$(printf '%s' "${p_status}" | "${REPO_ROOT}/scripts/mpm-py" "${REPO_ROOT}/scripts/destructive-cmd-guard.py" ${lang_arg} 2>/dev/null || true)"

  local ok=true
  if ! printf '%s' "${out_clean}" | grep -q '"decision"[[:space:]]*:[[:space:]]*"deny"'; then
    ok=false
  fi
  if ! printf '%s' "${out_status}" | grep -q '"decision"[[:space:]]*:[[:space:]]*"allow"'; then
    ok=false
  fi

  if [ "${ok}" = "true" ]; then
    return 0
  else
    return 1
  fi
}

cmd_status() {
  printf "Plugin slot : %s\n" "${TARGET_LINK}"
  printf "Kit repo    : %s\n" "${REPO_ROOT}"

  if [ -L "${TARGET_LINK}" ]; then
    local raw_target
    raw_target="$(readlink "${TARGET_LINK}")"
    local resolved_target="${raw_target}"
    if [[ "${raw_target}" != /* ]]; then
      resolved_target="$(dirname "${TARGET_LINK}")/${raw_target}"
    fi

    if [ -f "${resolved_target}/plugin.json" ]; then
      local ver
      ver="$(read_version "${resolved_target}/plugin.json")"
      printf "State       : INSTALLED (valid symlink)\n"
      printf "Target      : %s\n" "${raw_target}"
      printf "Edition     : %s\n" "$(detect_edition "${resolved_target}")"
      [ -n "${ver}" ] && printf "Version     : v%s\n" "${ver}"
      if [ -f "${resolved_target}/hooks.json" ]; then
        printf "Hook Guard  : ACTIVE (hooks.json present)\n"
      else
        printf "Hook Guard  : INACTIVE (hooks.json not found)\n"
      fi
      printf "Manage UI   : /plugin -> customization://%s\n" "${PLUGIN_DIR_NAME}"
    else
      printf "State       : BROKEN SYMLINK (target plugin.json not found)\n"
      printf "Target      : %s\n" "${raw_target}"
    fi
  elif [ -e "${TARGET_LINK}" ]; then
    printf "State       : NON-SYMLINK DIRECTORY/FILE PRESENT\n"
    printf "Warning     : %s exists and is not a symlink.\n" "${TARGET_LINK}"
    printf "              Re-run with --force or --migrate to back it up and replace it.\n"
  else
    printf "State       : NOT INSTALLED\n"
    printf "Install EN  : ./install.sh --lang en\n"
    printf "Install RU  : ./install.sh --lang ru\n"
  fi

  local pin_val
  pin_val="$(read_pinned_py)"
  if [ -n "${pin_val}" ]; then
    if is_valid_py "${pin_val}"; then
      printf "Python Pin  : %s (valid, v%s)\n" "${pin_val}" "$(get_py_version "${pin_val}")"
    else
      printf "Python Pin  : %s (INVALID or missing)\n" "${pin_val}"
    fi
  else
    printf "Python Pin  : NONE (unpinned)\n"
  fi

  local live_py
  live_py="$("${REPO_ROOT}/scripts/mpm-py" --print-python 2>/dev/null || true)"
  if [ -n "${live_py}" ] && is_valid_py "${live_py}"; then
    printf "Python Live : %s (v%s)\n" "${live_py}" "$(get_py_version "${live_py}")"
  else
    printf "Python Live : NOT FOUND (Python >=3.8 required)\n"
  fi

  local venv_dir="${REPO_ROOT}/.venv"
  if [ -d "${venv_dir}" ]; then
    local venv_py="${venv_dir}/bin/python3"
    [ ! -x "${venv_py}" ] && venv_py="${venv_dir}/bin/python"
    if [ -n "${venv_py}" ] && is_valid_py "${venv_py}"; then
      printf "Kit .venv   : PRESENT (%s, v%s)\n" "${venv_dir}" "$(get_py_version "${venv_py}")"
    else
      printf "Kit .venv   : BROKEN (%s)\n" "${venv_dir}"
    fi
  else
    printf "Kit .venv   : NONE\n"
  fi
}

cmd_doctor() {
  printf "%s\n\n" "=== Antigravity MPM Kit Doctor ==="
  printf "%s\n" "--- 1. Installation Status ---"
  cmd_status
  printf "\n%s\n" "--- 2. Python Environment Managers ---"
  local mgr
  for mgr in uv virtualenv poetry conda pyenv; do
    if command -v "${mgr}" >/dev/null 2>&1; then
      printf "  %-14s: AVAILABLE (%s)\n" "${mgr}" "$(command -v "${mgr}")"
    else
      printf "  %-14s: NOT FOUND\n" "${mgr}"
    fi
  done

  local live_py
  live_py="$("${REPO_ROOT}/scripts/mpm-py" --print-python 2>/dev/null || true)"
  if [ -n "${live_py}" ] && "${live_py}" -c "import venv" >/dev/null 2>&1; then
    printf "  %-14s: AVAILABLE (via %s)\n" "venv (stdlib)" "${live_py}"
  else
    printf "  %-14s: NOT FOUND\n" "venv (stdlib)"
  fi

  printf "\n%s\n" "--- 3. Python Resolution Origin ---"
  if [ -n "${AGY_MPM_PYTHON:-}" ] && is_valid_py "${AGY_MPM_PYTHON}"; then
    printf "  Origin        : \$AGY_MPM_PYTHON environment override (%s)\n" "${AGY_MPM_PYTHON}"
  elif [ -f "${PIN_FILE}" ] && [ -n "$(read_pinned_py)" ] && is_valid_py "$(read_pinned_py)"; then
    printf "  Origin        : Pinned file %s (%s)\n" "${PIN_FILE}" "$(read_pinned_py)"
  elif [ -d "${REPO_ROOT}/.venv" ] && is_valid_py "${REPO_ROOT}/.venv/bin/python3"; then
    printf "  Origin        : Kit-local .venv (%s)\n" "${REPO_ROOT}/.venv"
  elif [ -n "${VIRTUAL_ENV:-}" ] && is_valid_py "${VIRTUAL_ENV}/bin/python3"; then
    printf "  Origin        : Active virtualenv (%s)\n" "${VIRTUAL_ENV}"
  elif [ -n "${CONDA_PREFIX:-}" ] && is_valid_py "${CONDA_PREFIX}/bin/python3"; then
    printf "  Origin        : Active conda environment (%s)\n" "${CONDA_PREFIX}"
  elif command -v python3 >/dev/null 2>&1 && is_valid_py "$(command -v python3)"; then
    printf "  Origin        : System PATH (%s)\n" "$(command -v python3)"
  else
    printf "  Origin        : Toolchain search / fallback\n"
  fi

  printf "\n%s\n" "--- 4. Live Safety Guard Smoke Test ---"
  if run_guard_smoke_test; then
    printf "  Guard Smoke   : PASS (blocked 'git clean -fd', allowed 'git status')\n"
  else
    printf "  Guard Smoke   : FAIL (destructive-cmd-guard did not return expected decisions)\n"
    return 1
  fi

  printf "\n%s\n" "--- 5. Unit Test Suite (tests/test_guards.py) ---"
  local test_code=0
  AGY_MPM_SKIP_DOCTOR_TESTS=1 "${REPO_ROOT}/scripts/mpm-py" -m unittest discover -s "${REPO_ROOT}/tests" -p "test_guards.py" || test_code=$?
  if [ ${test_code} -eq 0 ]; then
    printf "  Test Suite    : PASS (all tests passed)\n"
  else
    printf "  Test Suite    : FAIL (exit code %d)\n" "${test_code}"
    return 1
  fi
  printf "\nAll doctor health checks passed.\n"
}

cmd_check_projects() {
  local dirs=("$@")
  if [ ${#dirs[@]} -eq 0 ]; then
    printf "Usage: ./install.sh --check-projects <dir1> [dir2 ...]\n" >&2
    return 1
  fi

  local total_issues=0
  printf "=== Checking Projects for Antigravity v2.3 Compatibility ===\n\n"

  local dir
  for dir in "${dirs[@]}"; do
    if [ ! -d "${dir}" ]; then
      printf "[SKIP]  %s (directory not found)\n" "${dir}"
      continue
    fi

    local proj_issues=()
    local gitignore_file="${dir}/.gitignore"
    if [ -e "${dir}/.git" ]; then
      if [ -f "${gitignore_file}" ]; then
        if ! grep -qE "^[[:space:]]*(\./)?\.agents/teamwork/?([[:space:]]|$)" "${gitignore_file}"; then
          proj_issues+=("Missing '.agents/teamwork/' in .gitignore")
        fi
      else
        proj_issues+=("Missing .gitignore file (needs '.agents/teamwork/')")
      fi
    elif [ -f "${gitignore_file}" ]; then
      if ! grep -qE "^[[:space:]]*(\./)?\.agents/teamwork/?([[:space:]]|$)" "${gitignore_file}"; then
        proj_issues+=("Missing '.agents/teamwork/' in .gitignore")
      fi
    fi

    local adapter_file=""
    if [ -f "${dir}/GEMINI.md" ]; then
      adapter_file="${dir}/GEMINI.md"
    elif [ -f "${dir}/AGENTS.md" ]; then
      adapter_file="${dir}/AGENTS.md"
    fi

    if [ -z "${adapter_file}" ]; then
      proj_issues+=("No Antigravity adapter found (GEMINI.md or AGENTS.md)")
    else
      if ! grep -qE "v2\.3|2\.3\.[0-9]" "${adapter_file}"; then
        proj_issues+=("Stale pre-v2.3 adapter in $(basename "${adapter_file}")")
      fi
    fi

    if [ ${#proj_issues[@]} -gt 0 ]; then
      printf "[STALE] %s:\n" "${dir}"
      local issue
      for issue in "${proj_issues[@]}"; do
        printf "  - %s\n" "${issue}"
      done
      printf "  Action needed: Run in workspace -> /kit-bootstrap --migrate\n\n"
      total_issues=$((total_issues + ${#proj_issues[@]}))
    else
      printf "[OK]    %s (adapter and .gitignore are up to date with v2.3)\n" "${dir}"
    fi
  done

  if [ ${total_issues} -gt 0 ]; then
    printf "\nNotice: %d compatibility issue(s) detected across inspected projects.\n" "${total_issues}"
  else
    printf "\nAll inspected projects are up to date.\n"
  fi
  return 0
}

cmd_migrate() {
  local lang="${1:-en}"
  local source_dir="${REPO_ROOT}"
  [ "${lang}" = "ru" ] && source_dir="${REPO_ROOT}/ru"

  printf "=== Antigravity MPM Kit Migration (v2.3.1) ===\n\n"

  # 1. Back up legacy non-symlink slot if encountered
  if [ -L "${TARGET_LINK}" ]; then
    rm -f "${TARGET_LINK}"
  elif [ -e "${TARGET_LINK}" ]; then
    local backup_path="${TARGET_LINK}.bak.$(date +%Y%m%d%H%M%S)"
    mv "${TARGET_LINK}" "${backup_path}"
    printf "Backed up legacy non-symlink plugin slot to: %s\n" "${backup_path}"
  fi

  # 2. Python discovery & verification
  local resolved_py=""
  resolved_py="$("${REPO_ROOT}/scripts/mpm-py" --print-python 2>/dev/null || true)"

  if [ -z "${resolved_py}" ] || ! is_valid_py "${resolved_py}"; then
    if command -v uv >/dev/null 2>&1; then
      printf "No system Python >=3.8 found. Creating isolated kit venv via uv...\n"
      if create_kit_venv "uv"; then
        resolved_py="${REPO_ROOT}/.venv/bin/python3"
        [ ! -x "${resolved_py}" ] && resolved_py="${REPO_ROOT}/.venv/bin/python"
      fi
    fi
  fi

  if [ -z "${resolved_py}" ] || ! is_valid_py "${resolved_py}"; then
    printf "Error: Python >=3.8 is required for agy-mpm-core safety hooks.\n" >&2
    printf "Please install Python >=3.8 via your package manager:\n" >&2
    printf "  macOS:  brew install python@3.11\n" >&2
    printf "  Ubuntu: sudo apt-get install python3 python3-venv\n" >&2
    printf "  or install uv: curl -LsSf https://astral.sh/uv/install.sh | sh\n" >&2
    printf "Aborting migration before installing hooks.\n" >&2
    return 1
  fi

  # 3. Pin Python
  if [ "${NO_PIN}" != "true" ]; then
    pin_python "${resolved_py}"
  fi

  # 4. Refresh symlink
  mkdir -p "${PLUGINS_ROOT}"
  ln -s "${source_dir}" "${TARGET_LINK}"
  printf "Linked %s -> %s\n" "${TARGET_LINK}" "${source_dir}"

  # 5. Live guard smoke test
  printf "Running live safety guard smoke test...\n"
  local smoke_lang=""
  [ "${lang}" = "ru" ] && smoke_lang="--lang ru"
  if run_guard_smoke_test "${smoke_lang}"; then
    printf "Guard smoke test: PASS\n"
  else
    printf "Error: Guard smoke test failed!\n" >&2
    return 1
  fi

  # 6. Check projects if passed
  if [ ${#CHECK_PROJECT_DIRS[@]} -gt 0 ]; then
    printf "\n"
    cmd_check_projects "${CHECK_PROJECT_DIRS[@]}"
  fi

  printf "\nMigration to v2.3.1 completed successfully!\n"
}

cmd_uninstall() {
  local removed_anything=false
  if [ -L "${TARGET_LINK}" ]; then
    local prev_target
    prev_target="$(readlink "${TARGET_LINK}")"
    rm -f "${TARGET_LINK}"
    printf "Removed symlink: %s (was -> %s)\n" "${TARGET_LINK}" "${prev_target}"
    removed_anything=true
  elif [ -e "${TARGET_LINK}" ]; then
    printf "Error: Refusing to uninstall %s because it is a real directory/file (not a symlink).\n" "${TARGET_LINK}" >&2
    printf "Move or inspect it manually to avoid accidental data loss.\n" >&2
    return 1
  fi

  if [ -f "${PIN_FILE}" ]; then
    rm -f "${PIN_FILE}"
    printf "Removed Python pin file: %s\n" "${PIN_FILE}"
    removed_anything=true
  fi

  if [ "${removed_anything}" = "false" ]; then
    printf "Nothing to uninstall: neither plugin symlink (%s) nor pin file (%s) exists.\n" "${TARGET_LINK}" "${PIN_FILE}"
  fi

  printf "Note: ~/.gemini/config/config.json and any kit virtual environment (%s/.venv) were left untouched.\n" "${REPO_ROOT}"
}

cmd_install() {
  local lang="$1"
  local force="$2"
  local custom_py="$3"
  local venv_backend="$4"
  local source_dir=""

  case "${lang}" in
    en)
      source_dir="${REPO_ROOT}"
      ;;
    ru)
      source_dir="${REPO_ROOT}/ru"
      ;;
    *)
      printf "Error: Unsupported language '%s'. Expected 'en' or 'ru'.\n" "${lang}" >&2
      exit 1
      ;;
  esac

  if [ ! -f "${source_dir}/plugin.json" ]; then
    printf "Error: Cannot find plugin manifest at '%s/plugin.json'.\n" "${source_dir}" >&2
    exit 1
  fi

  local resolved_py=""

  if [ -n "${custom_py}" ]; then
    if is_valid_py "${custom_py}"; then
      resolved_py="${custom_py}"
    else
      printf "Error: Specified Python executable '%s' is not executable or version is < 3.8.\n" "${custom_py}" >&2
      exit 1
    fi
  elif [ -n "${venv_backend}" ]; then
    if create_kit_venv "${venv_backend}"; then
      resolved_py="${REPO_ROOT}/.venv/bin/python3"
      [ ! -x "${resolved_py}" ] && resolved_py="${REPO_ROOT}/.venv/bin/python"
    else
      exit 1
    fi
  else
    resolved_py="$("${REPO_ROOT}/scripts/mpm-py" --print-python 2>/dev/null || true)"
    if [ -z "${resolved_py}" ] || ! is_valid_py "${resolved_py}"; then
      if command -v uv >/dev/null 2>&1; then
        printf "Error: Python >=3.8 not found.\n" >&2
        printf "uv is installed. You can create an isolated virtualenv by running:\n" >&2
        printf "  ./install.sh --venv\n" >&2
        exit 1
      else
        printf "Error: Python >=3.8 is required for agy-mpm-core safety hooks.\n" >&2
        printf "Please install Python >=3.8 via your package manager:\n" >&2
        printf "  macOS:  brew install python@3.11\n" >&2
        printf "  Ubuntu: sudo apt-get install python3 python3-venv\n" >&2
        printf "  or install uv: curl -LsSf https://astral.sh/uv/install.sh | sh\n" >&2
        exit 1
      fi
    fi
  fi

  if [ "${NO_PIN}" != "true" ] && [ -n "${resolved_py}" ]; then
    pin_python "${resolved_py}"
  fi

  mkdir -p "${PLUGINS_ROOT}"

  if [ -L "${TARGET_LINK}" ]; then
    rm -f "${TARGET_LINK}"
  elif [ -e "${TARGET_LINK}" ]; then
    if [ "${force}" != "true" ]; then
      printf "Error: '%s' already exists as a non-symlink directory or file.\n" "${TARGET_LINK}" >&2
      printf "Refusing to overwrite safely. Move it manually or pass --force or --migrate to back it up.\n" >&2
      exit 1
    fi
    local backup_path="${TARGET_LINK}.bak.$(date +%Y%m%d%H%M%S)"
    mv "${TARGET_LINK}" "${backup_path}"
    printf "Backed up existing non-symlink target to: %s\n" "${backup_path}"
  fi

  ln -s "${source_dir}" "${TARGET_LINK}"

  # Live smoke test
  local smoke_lang=""
  [ "${lang}" = "ru" ] && smoke_lang="--lang ru"
  if ! run_guard_smoke_test "${smoke_lang}"; then
    printf "Warning: Deletion shield smoke test failed after installation.\n" >&2
  fi

  local ver
  ver="$(read_version "${source_dir}/plugin.json")"
  printf "Installed %s (%s%s):\n" "${PLUGIN_DIR_NAME}" "${lang}" "${ver:+, v${ver}}"
  printf "  %s -> %s\n" "${TARGET_LINK}" "${source_dir}"
  [ -n "${resolved_py}" ] && printf "  Python runtime: %s (v%s)\n" "${resolved_py}" "$(get_py_version "${resolved_py}")"
  printf "\nNext steps in Google Antigravity:\n"
  printf "  1. Manage or toggle live via /plugin (customization://%s)\n" "${PLUGIN_DIR_NAME}"
  printf "  2. Open any project and run: /kit-bootstrap --lite | --full | --migrate or /kit-architecture\n"
}

ACTION="install"
LANG_CHOICE="en"
FORCE_INSTALL="false"
CUSTOM_PYTHON=""
VENV_BACKEND=""
NO_PIN="false"
CHECK_PROJECT_DIRS=()

while [ $# -gt 0 ]; do
  case "$1" in
    --lang)
      [ $# -lt 2 ] && { printf "Error: --lang requires an argument ('en' or 'ru').\n" >&2; exit 1; }
      LANG_CHOICE="$2"
      shift 2
      ;;
    --lang=*)
      LANG_CHOICE="${1#--lang=}"
      shift
      ;;
    --python)
      [ $# -lt 2 ] && { printf "Error: --python requires a path argument.\n" >&2; exit 1; }
      CUSTOM_PYTHON="$2"
      shift 2
      ;;
    --python=*)
      CUSTOM_PYTHON="${1#--python=}"
      shift
      ;;
    --venv)
      VENV_BACKEND="auto"
      shift
      ;;
    --venv=*)
      VENV_BACKEND="${1#--venv=}"
      shift
      ;;
    --no-pin)
      NO_PIN="true"
      shift
      ;;
    --status)
      ACTION="status"
      shift
      ;;
    --doctor)
      ACTION="doctor"
      shift
      ;;
    --migrate)
      ACTION="migrate"
      shift
      ;;
    --check-projects)
      if [ "${ACTION}" = "install" ]; then
        ACTION="check_projects"
      fi
      shift
      while [ $# -gt 0 ] && [[ "$1" != --* ]]; do
        CHECK_PROJECT_DIRS+=("$1")
        shift
      done
      ;;
    --check-projects=*)
      if [ "${ACTION}" = "install" ]; then
        ACTION="check_projects"
      fi
      IFS=',' read -r -a parsed_dirs <<< "${1#--check-projects=}"
      CHECK_PROJECT_DIRS+=("${parsed_dirs[@]}")
      shift
      ;;
    --uninstall)
      ACTION="uninstall"
      shift
      ;;
    --force)
      FORCE_INSTALL="true"
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      printf "Error: Unknown argument '%s'. Run './install.sh --help' for usage.\n" "$1" >&2
      exit 1
      ;;
  esac
done

case "${ACTION}" in
  status)
    cmd_status
    ;;
  doctor)
    cmd_doctor
    if [ ${#CHECK_PROJECT_DIRS[@]} -gt 0 ]; then
      printf "\n"
      cmd_check_projects "${CHECK_PROJECT_DIRS[@]}"
    fi
    ;;
  migrate)
    cmd_migrate "${LANG_CHOICE}"
    ;;
  check_projects)
    cmd_check_projects "${CHECK_PROJECT_DIRS[@]}"
    ;;
  uninstall)
    cmd_uninstall
    ;;
  install)
    cmd_install "${LANG_CHOICE}" "${FORCE_INSTALL}" "${CUSTOM_PYTHON}" "${VENV_BACKEND}"
    ;;
esac
